(function () {
  "use strict";
  var COLORS = { nearest: "#ba5d18", greedy: "#3266ad", exact: "#23754a" };
  var NS = "http://www.w3.org/2000/svg";
  function el(tag, attrs, text) {
    var e = document.createElement(tag);
    Object.keys(attrs || {}).forEach(function (k) { e.setAttribute(k, attrs[k]); });
    if (text !== undefined) e.textContent = text;
    return e;
  }
  function svg(tag, attrs, text) {
    var e = document.createElementNS(NS, tag);
    Object.keys(attrs || {}).forEach(function (k) { e.setAttribute(k, attrs[k]); });
    if (text !== undefined) e.textContent = text;
    return e;
  }
  function pct(v) { return v.toFixed(1) + "%"; }
  function table(target, headers, rows) {
    target.replaceChildren();
    var head = el("tr");
    headers.forEach(function (h) { head.appendChild(el("th", { scope: "col" }, h)); });
    var thead = el("thead"); thead.appendChild(head); target.appendChild(thead);
    var body = el("tbody");
    rows.forEach(function (cells) {
      var tr = el("tr");
      if (cells.title) tr.setAttribute("title", cells.title);
      cells.forEach(function (c, i) { tr.appendChild(el(i === 0 ? "th" : "td", i === 0 ? { scope: "row" } : {}, c)); });
      body.appendChild(tr);
    });
    target.appendChild(body);
  }
  function bars(target, items) {
    target.replaceChildren();
    items.forEach(function (item, i) {
      var y = 10 + i * 45;
      target.appendChild(svg("text", { x: 0, y: y + 22, "font-size": 13, fill: "currentColor" }, item.label));
      target.appendChild(svg("rect", { x: 200, y: y, width: 440, height: 30, fill: "#eee" }));
      target.appendChild(svg("rect", { x: 200, y: y, width: Math.max(0, Math.min(100, item.value)) * 4.4, height: 30, fill: item.color }));
      target.appendChild(svg("text", { x: 648, y: y + 21, "font-size": 13, fill: "currentColor" }, pct(item.value)));
    });
  }
  function show(data) {
    var s = data.summary;
    document.getElementById("intro").textContent =
      "Results from " + data.scenarios + " simulated scenarios, each solved by all three algorithms. " +
      "The exact branch-and-bound solver is the reference for the best possible answer.";
    table(document.getElementById("summary-table"),
      ["Algorithm", "Solved optimally", "Visits vs best", "Avg distance vs best", "Avg runtime", "Slowest run", "Avg states checked"],
      s.map(function (a) {
        return [a.name, pct(a.optimalPct), pct(a.visitsPctOfOptimal), a.avgDistanceRatio.toFixed(3) + "×",
          a.avgRuntimeMs.toFixed(2) + " ms", a.maxRuntimeMs.toFixed(1) + " ms", Math.round(a.avgStates).toString()];
      }));
    bars(document.getElementById("optimal-chart"), s.map(function (a) { return { label: a.name, value: a.optimalPct, color: COLORS[a.id] }; }));
    bars(document.getElementById("visits-chart"), s.map(function (a) { return { label: a.name, value: a.visitsPctOfOptimal, color: COLORS[a.id] }; }));
    table(document.getElementById("family-table"),
      ["Scenario type", "Scenarios", "Nearest neighbour", "Greedy insertion", "Branch and bound"],
      data.families.map(function (f) {
        var row = [f.family, String(f.scenarios), pct(f.optimalPct.nearest), pct(f.optimalPct.greedy), pct(f.optimalPct.exact)];
        row.title = "Visits vs best — nearest " + pct(f.visitsPctOfOptimal.nearest) + ", greedy " + pct(f.visitsPctOfOptimal.greedy);
        return row;
      }));
    document.getElementById("method").textContent =
      "Scenarios were generated by a tester who had only the written specification, not the source code, and were checked " +
      "against an independent brute-force solver. Each has up to 8 customers with random positions, time windows, periods and speeds, " +
      "plus edge cases (tight deadlines, clustered and collinear points, duplicate coordinates, late starts). " +
      "Scenario types that deliberately hit search limits (" + data.excludedFamilies.join(", ") + ") are excluded here because the " +
      "exact solver is not a reference when it is cut short. Runtimes come from very small instances, so they show relative cost, not scaling.";
  }
  fetch("/evaluation-data.json", { cache: "no-store" })
    .then(function (r) { if (!r.ok) throw new Error("HTTP " + r.status); return r.json(); })
    .then(show)
    .catch(function (e) {
      var n = document.getElementById("notice");
      n.textContent = "Could not load evaluation data: " + e.message; n.hidden = false;
      document.getElementById("intro").textContent = "";
    });
})();
